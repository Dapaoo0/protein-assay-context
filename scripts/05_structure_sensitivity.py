def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _download_structure(pdb_id: str, directory: Path) -> tuple[Path, dict[str, object]]:
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{pdb_id.lower()}.pdb"
    url = f"https://files.rcsb.org/download/{pdb_id}.pdb"
    if not path.exists():
        with urllib.request.urlopen(url, timeout=60) as response:
            path.write_bytes(response.read())
    metadata_url = f"https://data.rcsb.org/rest/v1/core/entry/{pdb_id}"
    with urllib.request.urlopen(metadata_url, timeout=60) as response:
        metadata = json.loads(response.read().decode("utf-8"))
    exptl = (metadata.get("exptl") or [{}])[0]
    refine = (metadata.get("refine") or [{}])[0]
    resolution = refine.get("ls_dres_high")
    if resolution is None:
        combined = (metadata.get("rcsb_entry_info") or {}).get("resolution_combined") or []
        resolution = combined[0] if combined else None
    return path, {
        "structure_id": pdb_id,
        "chain": "A",
        "official_url": url,
        "metadata_url": metadata_url,
        "retrieved_at": datetime.fromtimestamp(path.stat().st_mtime, UTC).isoformat(),
        "sha256": _sha256(path),
        "experimental_method": exptl.get("method"),
        "resolution_angstrom": resolution,
    }


def _download_uniprot_annotation(accession: str, directory: Path) -> dict[str, object]:
    """Retrieve independent UniProt feature provenance for frozen site positions."""
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"uniprot_{accession}.txt"
    url = f"https://rest.uniprot.org/uniprotkb/{accession}.txt"
    if not path.exists():
        with urllib.request.urlopen(url, timeout=60) as response:
            path.write_bytes(response.read())
    text = path.read_text(encoding="utf-8", errors="replace")
    versions = [line.split("entry version", 1)[1].strip().rstrip(".") for line in text.splitlines() if "entry version" in line]
    features = [line.strip() for line in text.splitlines() if line.startswith(("FT   ACT_SITE", "FT   BINDING"))]
    return {"accession": accession, "official_url": url, "retrieved_at": datetime.fromtimestamp(path.stat().st_mtime, UTC).isoformat(), "sha256": _sha256(path), "entry_version": versions[0] if versions else None, "site_features": features}


