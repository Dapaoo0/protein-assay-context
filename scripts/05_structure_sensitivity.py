def _structure_maps(work_dir: Path) -> tuple[pd.DataFrame, list[dict[str, object]]]:
    sequences = _load_sequences()
    rows: list[pd.DataFrame] = []
    provenance: list[dict[str, object]] = []
    for protein, spec in PRIMARY_STRUCTURES.items():
        protein_id = {"CYP2C9": "CP2C9_HUMAN", "PTEN": "PTEN_HUMAN"}[protein]
        path, meta = _download_structure(spec["pdb_id"], work_dir)
        annotation = _download_uniprot_annotation(spec["uniprot"], work_dir)
        if meta["sha256"] != spec["structure_sha256"]:
            raise ValueError(f"frozen structure SHA256 mismatch for {spec['pdb_id']}; refusing to overwrite source")
        if annotation["sha256"] != spec["uniprot_sha256"]:
            raise ValueError(f"frozen UniProt SHA256 mismatch for {spec['uniprot']}; refusing to overwrite source")
        mapped = map_structure(sequences[protein_id], str(path), spec["chain"], functional_positions=spec["functional_positions"], functional_site_source=spec["site_source"])
        mapped.insert(0, "protein", protein)
        mapped.insert(1, "structure_id", spec["pdb_id"])
        rows.append(mapped)
        meta.update({"protein": protein, "reference_sequence_hash": hashlib.sha256(sequences[protein_id].encode()).hexdigest(), "mapping_identity": mapped.attrs["mapping_identity"], "mapping_coverage": mapped.attrs["mapping_coverage"], "sequence_mapping_rule": "global Needleman-Wunsch; identity >=0.95 and reference coverage >=0.65", "functional_site_source": spec["site_source"], "functional_site_positions": spec["functional_positions"], "independent_annotation": annotation, "confidence_rule": mapped.attrs["confidence_definition"]})
        provenance.append(meta)
    return pd.concat(rows, ignore_index=True), provenance


