def _figure6(features: pd.DataFrame, primary: pd.DataFrame, output: Path) -> pd.DataFrame:
    # Cases are deterministically selected post-analysis using a recorded rule.
    joined = primary.copy()
    missing_features = [column for column in ("accessibility", "site_distance", "mapping_status") if column not in joined]
    if missing_features:
        joined = joined.merge(features[["protein", "position", *missing_features]], on=["protein", "position"], how="left", validate="many_to_one")
    impaired = joined.loc[joined["primary_endpoint"].eq("function-impaired") & joined["prediction"].notna()]
    false_negative = impaired.loc[impaired["prediction"].lt(0.5)].sort_values(["prediction", "protein", "position", "variant"]).head(1)
    true_positive = impaired.loc[impaired["prediction"].ge(0.5)].sort_values(["prediction", "protein", "position", "variant"], ascending=[False, True, True, True]).head(1)
    uncertain_pool = joined.loc[joined["function_label"].eq("uncertain")]
    medians = joined.groupby("protein")["ESM1v_single_impairment"].median()
    uncertain = uncertain_pool.assign(_distance=(uncertain_pool["ESM1v_single_impairment"] - uncertain_pool["protein"].map(medians)).abs()).sort_values(["_distance", "protein", "position", "variant"]).head(1)
    cases = pd.concat([false_negative.assign(case="false negative"), true_positive.assign(case="true positive"), uncertain.assign(case="uncertain")], ignore_index=True)
    fig, axes = plt.subplots(3, 1, figsize=(12, 10), sharex=False, gridspec_kw={"height_ratios": [3, 1, 0.8]})
    for protein, group in features.groupby("protein", sort=True):
        axes[0].scatter(group["position"], group["site_distance"], s=12, alpha=0.55, label=protein)
    for row in cases.itertuples(index=False):
        if pd.notna(row.site_distance):
            axes[0].scatter(row.position, row.site_distance, s=55, edgecolor="black", linewidth=0.8)
            axes[0].annotate(f"{row.case}: {row.protein} {row.variant}", (row.position, row.site_distance), xytext=(4, 4), textcoords="offset points", fontsize=8)
    axes[0].set_ylabel("Minimum heavy-atom distance to annotated site (Å)")
    axes[0].set_title("Figure 6. Structure/error map; proximity is descriptive, not allostery")
    axes[0].legend()
    for protein, group in features.groupby("protein", sort=True):
        axes[1].plot(group["position"], group["accessibility"], ".", label=protein)
    axes[1].set_xlabel("Reference residue position")
    axes[1].set_ylabel("Relative solvent accessibility")
    axes[2].axis("off")
    lines = []
    for row in cases.itertuples(index=False):
        probability = getattr(row, "prediction", np.nan)
        probability_text = f"OOF p={probability:.3f}" if pd.notna(probability) else "OOF p=not available"
        mapping = getattr(row, "mapping_status", "missing")
        if mapping != "mapped" or pd.isna(getattr(row, "site_distance", np.nan)):
            mapping = "unmapped / no structural distance available"
        lines.append(f"{row.case}: {row.protein} {row.variant} | {probability_text} | phenotype={getattr(row, 'function_label', 'not available')} | {mapping}")
    axes[2].text(0.01, 0.95, "Deterministically selected post-analysis using a recorded rule (not mechanisms or clinical claims):\n" + "\n".join(lines), va="top", fontsize=8)
    fig.subplots_adjust(left=0.10, right=0.96, bottom=0.08, top=0.88, hspace=0.35)
    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output, dpi=180)
    plt.close(fig)
    return cases


